"""
Experiment 7 - derive a right-sized container from MEASURED usage of the
over-provisioned deployment, and write a config file for the "after" run.

Rule (documented in the report):
  required vCPU   = p95 CPU cores used at the design load / 0.70
                    (target: p95 utilisation <= 70 % of the limit, the usual right-sizing rule)
  required memory = peak memory x (new workers / old workers) x 1.5 headroom
  -> rounded UP to the smallest valid AWS Fargate task size that satisfies both
  workers         = max(1, round(2 x vCPU)), threads = 4

Usage: python bench/rightsize.py results/exp7_before/exp7_before_2vcpu_4gb.json \
           --out bench/configs_exp7_after.json
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

# valid Fargate (vCPU -> memory MiB options)
FARGATE = {
    0.25: [512, 1024, 2048],
    0.5: [1024, 2048, 3072, 4096],
    1: [2048, 3072, 4096, 5120, 6144, 7168, 8192],
    2: [4096 + 1024 * i for i in range(13)],
    4: [8192 + 1024 * i for i in range(23)],
}
TARGET_CPU_UTIL = 0.70
CPU_HEADROOM = 1 / TARGET_CPU_UTIL
MEM_HEADROOM = 1.5


def recommend(before: dict) -> dict:
    cfg = before["config"]
    res = before["fixed_rate"]["resources"]
    need_cpu = res["cpu_cores_p95"] * CPU_HEADROOM
    cpu = next(c for c in sorted(FARGATE) if c >= need_cpu)
    workers = max(1, round(2 * cpu))
    need_mem = res["mem_mib_max"] * (workers / cfg["workers"]) * MEM_HEADROOM
    mem = next((m for m in FARGATE[cpu] if m >= need_mem), None)
    while mem is None:                       # memory forces a bigger CPU tier
        cpu = next(c for c in sorted(FARGATE) if c > cpu)
        mem = next((m for m in FARGATE[cpu] if m >= need_mem), None)
    return {
        "measured": {"cpu_cores_mean": res["cpu_cores_mean"], "cpu_cores_p95": res["cpu_cores_p95"],
                     "mem_mib_max": res["mem_mib_max"],
                     "cpu_util_of_limit_mean_pct": res["cpu_util_of_limit_mean_pct"],
                     "mem_util_of_limit_max_pct": res["mem_util_of_limit_max_pct"]},
        "rule": {"target_p95_cpu_util": TARGET_CPU_UTIL, "mem_headroom": MEM_HEADROOM,
                 "required_vcpu": round(need_cpu, 3), "required_mem_mib": round(need_mem, 1)},
        "before": {k: cfg[k] for k in ("cpus", "memory_mb", "workers", "threads")},
        "after": {"cpus": cpu, "memory_mb": mem, "workers": workers, "threads": 4},
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("before_json")
    ap.add_argument("--out", default="bench/configs_exp7_after.json")
    a = ap.parse_args()
    rec = recommend(json.loads(Path(a.before_json).read_text()))
    af = rec["after"]
    name = f"exp7_after_{af['cpus']}vcpu_{af['memory_mb'] / 1024:g}gb"
    Path(a.out).write_text(json.dumps({
        "description": "Experiment 7 - right-sized deployment generated by bench/rightsize.py",
        "recommendation": rec,
        "configs": [{"name": name, **af}],
    }, indent=2))
    print(json.dumps(rec, indent=2))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
